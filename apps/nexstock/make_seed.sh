#!/bin/sh
# Regenerate seed.sql from NexStock's own seed scripts. Run this only when the pinned
# NexStock commit changes; commit the new seed.sql so every computer loads the same data.
set -eu
cd "$(dirname "$0")"
compose="docker compose -f compose.yaml"

$compose down --volumes --remove-orphans
$compose up --detach --wait db
# The seed scripts use random values; a fixed seed keeps regeneration repeatable.
$compose run --rm --no-deps api sh -c \
  "alembic upgrade head && python -c \"import random, runpy; random.seed(4907); runpy.run_path('scripts/seed_all.py', run_name='__main__')\""

{
  echo "-- Generated by make_seed.sh from NexStock's seed scripts. Do not edit by hand."
  echo "DROP SCHEMA IF EXISTS public CASCADE;"
  $compose exec -T db pg_dump --username nexstock --no-owner --no-privileges --schema public nexstock
} > seed.sql

$compose down --volumes
echo "Wrote $(pwd)/seed.sql"
